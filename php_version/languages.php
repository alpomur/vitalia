/**
 * Dil çevirisi al
 */
function t($key, $lang = 'tr') {
    global $translations;
    $t = $translations[$lang] ?? $translations['tr'];
    return $t[$key] ?? $key;
}

/**
 * Desteklenen dilleri al
 */
function getSupportedLanguages() {
    global $translations;
    $langs = [];
    foreach ($translations as $code => $t) {
        $langs[] = [
            'code' => $code,
            'name' => $t['name'],
            'flag' => $t['flag'],
            'dir' => $t['dir'] ?? 'ltr'
        ];
    }
    return $langs;
}
